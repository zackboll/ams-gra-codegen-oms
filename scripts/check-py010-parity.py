#!/usr/bin/env python3
"""Require VisibleAscii-free model/API/codec bytes to match the PY-009 baseline."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generator', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    frozen = json.loads((ROOT / 'tests/fixtures/python-visible-ascii/visible-free-parity.json').read_text())
    actual = []
    for row in frozen:
        fixture = ROOT / 'tests/fixtures' / row['fixture']
        dest = args.output / (row['fixture'].replace('-', '_') + '_' + row['world'].replace('-', '_') + '_' + str(row['codec']))
        cmd = [str(args.generator.resolve()), 'service-generate', '--schema', str(fixture / 'oam.xsd'),
               '--contract', str(fixture / 'service.yaml'), '--language', 'python', '--world', row['world'],
               '--output', str(dest)] + (['--with-codec'] if row['codec'] else [])
        subprocess.run(cmd, capture_output=True, text=True, check=True)
        actual.append(dict(row, files={p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                                       for p in sorted(dest.glob('*.py'))}))
    (args.output / 'parity.json').write_text(json.dumps(actual, indent=2) + '\n')
    if actual != frozen:
        raise RuntimeError('VisibleAscii-free generated bytes differ from PY-009')
    print('PY010 VISIBLE-FREE BYTE PARITY: PASSED selections=20 sources=50')


if __name__ == '__main__':
    main()